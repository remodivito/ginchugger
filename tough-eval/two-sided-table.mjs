// Prints the customer-side and vendor-side playbooks side by side, one topic per row, for reading and review.
// Usage: node tough-eval/two-sided-table.mjs > tough-eval/TWO-SIDED-PLAYBOOKS.md
import { readFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const here = path.dirname(fileURLToPath(import.meta.url));
const customer = JSON.parse(readFileSync(path.join(here, 'playbook.json'), 'utf8'));
const vendor = JSON.parse(readFileSync(path.join(here, 'playbook-vendor.json'), 'utf8'));
const cell = s => String(s ?? '—').replace(/\|/g, '\\|').replace(/\n/g, ' ');
console.log(`# The two playbooks, side by side\n\nGenerated by two-sided-table.mjs from playbook.json (customer side, v${customer.version}) and playbook-vendor.json (vendor side, v${vendor.version}). Both take the clean Common Paper CSA v2.1 as compliant; they differ in which direction of change is a departure and how far each side will go. The vendor side's \`source\` column records the Common Paper rationale or market figure behind the position (see ../common-paper-notes.md).\n`);
for (let i = 0; i < customer.rules.length; i++) {
  const c = customer.rules[i], v = vendor.rules[i];
  console.log(`## ${c.title} (${c.id} / ${v.id})\n\n| | Customer side | Vendor side |\n|---|---|---|`);
  for (const k of ['preferred', 'acceptable', 'escalation', 'hardLine']) console.log(`| ${k} | ${cell(c[k])} | ${cell(v[k])} |`);
  console.log(`\n*Source:* ${v.source}\n`);
}
