// P8: clean-copy calibration requests and their summary. Each clean document is reviewed on each side three times by
// each authoring family under the product prompt: 2 documents x 2 sides x 3 families x 3 repeats = 36 reviews a pass.
//   requests  writes <root>/calibration/pass-<k>/requests.json (one entry per review: id, document, side, family,
//             executor, model, repeat, variant file, playbook, output file, trace dir, environment) and run.sh, which
//             runs every request without an `ok` result through review-one.mjs (development runs; the canary is removed
//             by review-one). Clean variants: <root>/calibration/CLEAN-csa.json, CLEAN-nda.json.
//   summary   reads a pass's results and lists, per document and side, every paragraph flagged by a family (a flag is
//             status "attention" with decision other than "accept", as score.mjs), marking those flagged by two or more
//             families: the candidate faults P8 examines. Writes <root>/calibration/pass-<k>/summary.json.
// Usage: node tough-eval/v2/calibration.mjs requests [--pass 1] [--root v2] [--families opus,glm,deepseek]
//        node tough-eval/v2/calibration.mjs summary [--pass 1] [--root v2]
//        zsh tough-eval/v2/calibration/pass-1/run.sh [opus|glm|deepseek]     (from outputs/)
import { existsSync, readFileSync, writeFileSync, mkdirSync, chmodSync } from 'node:fs';
import path from 'node:path';
import { SIDES, AUTHORS, readJson, writeJson, EVAL } from './lib/common.mjs';
import { MODELS, MAX_OUTPUT_TOKENS } from './lib/call.mjs';
import { rootAbs, rootRel } from './lib/store.mjs';
import { stripCanary } from './canary.mjs';
import { args } from './author.mjs';

export const REPEATS = 3;
const shq = s => `'${String(s).replace(/'/g, `'\\''`)}'`;

export function requests({ root = 'v2', pass = 1, families = AUTHORS } = {}) {
  const abs = rootAbs(root), rel = rootRel(root), dir = path.join(abs, 'calibration', `pass-${pass}`); mkdirSync(dir, { recursive: true });
  for (const d of ['csa', 'nda']) { const base = stripCanary(readJson(`v2/base-${d}.json`)); writeJson(path.join(abs, 'calibration', `CLEAN-${d}.json`), { ...base, id: `CLEAN-${d}` }); }
  const list = [];
  for (const [key, s] of Object.entries(SIDES)) for (const family of families) for (let r = 1; r <= REPEATS; r++) {
    const m = MODELS[family], id = `CAL-${key}-${family}-r${r}`;
    list.push({ id, document: s.document, side: s.side, family, repeat: r, executor: m.executor, model: m.model, effort: m.effort || 'medium',
      variant: `${rel}/calibration/CLEAN-${s.document}.json`, playbook: s.playbook, out: `${rel}/calibration/pass-${pass}/results/${id}.json`, traceDir: `${rel}/calibration/pass-${pass}/traces/${id}`,
      env: m.executor === 'claude' ? { REVIEW_EXECUTOR: 'claude', REVIEW_MODEL: m.model, REVIEW_EFFORT: m.effort }
        : { REVIEW_EXECUTOR: 'openai', REVIEW_MODEL: m.model, REVIEW_EFFORT: 'medium', OPENAI_BASE_URL: m.baseUrl, REVIEW_MAX_OUTPUT_TOKENS: String(MAX_OUTPUT_TOKENS), OPENAI_API_KEY: `$${m.keyEnv}` } });
  }
  writeJson(path.join(dir, 'requests.json'), { format: 'tough-eval-calibration-requests/1', pass, createdAt: new Date().toISOString(), prompt: 'product (contract-review/prompts/review.md)', mode: 'third-party, no baseline', requests: list });
  // The runner: skips a request whose result is ok; Munito requests one at a time; the key is read from contract-review/.env.
  const lines = ['#!/bin/zsh', '# Generated by tough-eval/v2/calibration.mjs. Run from outputs/: zsh ' + `tough-eval/${rel}/calibration/pass-${pass}/run.sh [family]`, 'set -u', `cd "$(dirname "$0")/${Array(rel.split('/').length + 3).fill('..').join('/')}" || exit 1`,
    '[ -f contract-review/.env ] && export MUNITO_API_KEY="${MUNITO_API_KEY:-$(grep ^MUNITO_API_KEY= contract-review/.env | cut -d= -f2-)}"',
    'only="${1:-}"', 'done_ok() { [ -f "$1" ] && grep -q \'"ok": true\' "$1"; }'];
  for (const q of list) {
    const env = Object.entries(q.env).map(([k, v]) => `${k}=${v.startsWith('$') ? `"${v}"` : shq(v)}`).join(' ');
    lines.push(`{ [ -z "$only" ] || [ "$only" = ${q.family} ]; } && { done_ok tough-eval/${q.out} || { mkdir -p tough-eval/${q.traceDir} "$(dirname tough-eval/${q.out})"; echo "${q.id} $(date -u +%H:%M)"; REVIEW_TRACE_DIR=tough-eval/${q.traceDir} ${env} node tough-eval/review-one.mjs tough-eval/${q.variant} tough-eval/${q.out} live tough-eval/${q.playbook}; }; }`);
  }
  const sh = path.join(dir, 'run.sh'); writeFileSync(sh, lines.join('\n') + '\n'); chmodSync(sh, 0o755);
  return { requests: list.length, dir };
}

const flagged = f => f.status === 'attention' && f.decision !== 'accept';
export function summary({ root = 'v2', pass = 1 } = {}) {
  const dir = path.join(rootAbs(root), 'calibration', `pass-${pass}`); const req = readJson(path.join(dir, 'requests.json')).requests;
  const out = {};
  for (const q of req) {
    const key = `${q.document}-${q.side}`; out[key] ||= { reviews: 0, usable: 0, paragraphs: {} };
    const f = path.join(EVAL, q.out); out[key].reviews++; if (!existsSync(f)) continue; const r = JSON.parse(readFileSync(f, 'utf8')); if (!r.ok) continue; out[key].usable++;
    for (const x of r.findings.filter(flagged)) { const p = (out[key].paragraphs[x.paragraphId] ||= { families: {}, rules: {} }); p.families[q.family] = (p.families[q.family] || 0) + 1; for (const id of x.ruleIds || []) p.rules[id] = (p.rules[id] || 0) + 1; }
  }
  for (const v of Object.values(out)) for (const [pid, p] of Object.entries(v.paragraphs)) p.candidateFault = Object.keys(p.families).length >= 2;
  const candidates = Object.entries(out).flatMap(([key, v]) => Object.entries(v.paragraphs).filter(([, p]) => p.candidateFault).map(([pid, p]) => ({ side: key, paragraph: pid, families: p.families, rules: p.rules })));
  writeJson(path.join(dir, 'summary.json'), { format: 'tough-eval-calibration-summary/1', pass, at: new Date().toISOString(), bySide: out, candidates });
  return { candidates };
}

if (process.argv[1] && import.meta.url.endsWith(path.basename(process.argv[1]))) {
  const [cmd] = process.argv.slice(2); const o = args(process.argv.slice(3)); const opts = { root: o.root || 'v2', pass: Number(o.pass || 1), ...(o.families ? { families: String(o.families).split(',') } : {}) };
  if (cmd === 'requests') console.log(JSON.stringify(requests(opts))); else if (cmd === 'summary') console.log(JSON.stringify(summary(opts), null, 1)); else { console.error('Usage: calibration.mjs requests|summary [--pass k] [--root v2]'); process.exit(2); }
}
